export interface PictoSpec { view: 'front' | 'back'; hl: Group[] }
const N4 = [[1, 0], [-1, 0], [0, 1], [0, -1]] as const;

/** 선분 위의 칸들 (그림 좌표 → 칸, 왼쪽 반과 거울 쪽 모두) */
function lineCells(a: Pt, b: Pt): [number, number][] {
  const toCell = ([x, y]: Pt): Pt => [CX + (x - MIDX) * S, (y - Y0) * S];
  const [ax, ay] = toCell(a), [bx, by] = toCell(b);
  const n = Math.ceil(Math.max(Math.abs(bx - ax), Math.abs(by - ay))) + 1;
  const out: [number, number][] = [];
  for (let i = 0; i <= n; i++) {
    const x = Math.floor(ax + ((bx - ax) * i) / n), y = Math.floor(ay + ((by - ay) * i) / n);
    out.push([x, y], [2 * CX - x, y]);
  }
  return out;
}

export function drawPicto(spec: PictoSpec): Grid {
  const W = PICTO_W, H = PICTO_H;
  const pieces = FRONT;
  const on = new Set<Group>(spec.hl);
  if (on.has('legs')) on.add('calves');
  // 칸 → 그림 좌표 (왼쪽 반으로 접기)
  const toImg = (x: number, y: number): Pt => { const gx = x > CX ? 2 * CX - x : x; return [Math.min(MIDX, MIDX + (gx - CX + 0.5) / S), Y0 + (y + 0.5) / S]; };
  const sil: number[][] = Array.from({ length: H }, () => Array(W).fill(0));
  const lab: number[][] = Array.from({ length: H }, () => Array(W).fill(-1));
  for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) {
    const [ix, iy] = toImg(x, y);
    const right = x > CX;
    if (inPoly(ix, iy, HEAD) || inPoly(ix, iy, HAND)) { sil[y]![x] = 2; lab[y]![x] = -2; continue; }
    if (!(inPoly(ix, iy, BODY) || inPoly(ix, iy, ARM) || inPoly(ix, iy, FOOT))) continue;
    sil[y]![x] = 1;
    const i = pieces.findIndex((p) => inPoly(ix, iy, p.poly));
    if (i >= 0) {
      const p = pieces[i]!;
      const band = p.bands?.filter((b) => iy > b).length ?? 0;
      const k = p.merge ? pieces.findIndex((q) => q.merge === p.merge) : i;
      lab[y]![x] = ((k * 8 + band) * 2 + (right && p.seam !== false ? 1 : 0)) * 64 + i;
    }
  }
  // 조각에 안 걸린 칸은 가까운 조각을 따름
  for (let pass = 0; pass < 20; pass++) {
    let changed = false;
    const next = lab.map((r) => [...r]);
    for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) {
      if (sil[y]![x] !== 1 || lab[y]![x]! >= 0) continue;
      for (const [dx, dy] of N4) { const o = lab[y + dy]?.[x + dx]; if (o !== undefined && o >= 0 && (x > CX) === (x + dx > CX)) { next[y]![x] = o; changed = true; break; } }
    }
    for (let y = 0; y < H; y++) lab[y] = next[y]!;
    if (!changed) break;
  }
  const inBody = (x: number, y: number) => (sil[y]?.[x] ?? 0) > 0;
  const line = (l: number) => (l < 0 ? l : Math.floor(l / 64));
  const g = blank(W, H);
  for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) {
    if (!inBody(x, y)) continue;
    if (N4.some(([dx, dy]) => !inBody(x + dx, y + dy))) { g[y]![x] = 'L'; continue; }
    const l = lab[y]![x]!;
    const right = x > CX;
    const sx = right ? x - 1 : x + 1;
    const other = (xx: number, yy: number) => { const o = lab[yy]?.[xx]; return o !== undefined && inBody(xx, yy) && line(o) !== line(l); };
    if ((!(right && sx <= CX) && other(sx, y)) || other(x, y + 1)) { g[y]![x] = 'L'; continue; }
    const piece = l >= 0 ? pieces[l % 64] : undefined;
    g[y]![x] = piece?.group && on.has(piece.group) ? 'r' : 'f';
  }
  for (const [a, b] of SKIN_LINES) for (const [x, y] of lineCells(a!, b!)) if (sil[y]?.[x] === 2) g[y]![x] = 'L';
  return g;
}
