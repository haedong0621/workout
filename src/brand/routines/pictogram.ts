export interface PictoSpec { view: 'front' | 'back'; hl: Group[]; heart?: boolean }
const N4 = [[1, 0], [-1, 0], [0, 1], [0, -1]] as const;
const GAP = 2;   // 살펴보는 거리
const EDGE = 2;  // 가장자리 틈: 바깥에서 이 거리 안이면 바탕(조각 사이 틈과 같은 2칸)

/** 가슴 가운데 하트 (유산소) */
function drawHeart(g: Grid) {
  const hx = CX, hy = Math.round((272 - Y0) * S), R = 10.5;
  const inside = (x: number, y: number) => { const u = (x - hx) / R, v = -(y - hy) / R + 0.1; return (u * u + v * v - 1) ** 3 - u * u * v ** 3 <= 0; };
  for (let y = 0; y < g.length; y++) for (let x = 0; x < g[0]!.length; x++) {
    if (!inside(x, y)) continue;
    g[y]![x] = N4.some(([dx, dy]) => !inside(x + dx, y + dy)) ? 'b' : 'r';
  }
  for (const [dx, dy] of [[-6, -4], [-7, -3], [-7, -2], [-5, -5]] as const) if (g[hy + dy]?.[hx + dx] === 'r') g[hy + dy]![hx + dx] = 'f';
}

export function drawPicto(spec: PictoSpec): Grid {
  const W = PICTO_W, H = PICTO_H;
  const back = spec.view === 'back';
  const pieces = back ? BACK : FRONT;
  const body = back ? BODY_BACK : BODY, foot = back ? FOOT_BACK : FOOT;
  const on = new Set<Group>(spec.hl);
  if (on.has('legs')) on.add('calves');
  // 칸 → 그림 좌표 (왼쪽 반으로 접기)
  const toImg = (x: number, y: number): Pt => { const gx = x > CX ? 2 * CX - x : x; return [Math.min(MIDX, MIDX + (gx - CX + 0.5) / S), Y0 + (y + 0.5) / S]; };
  const sil: number[][] = Array.from({ length: H }, () => Array(W).fill(0));
  const lab: number[][] = Array.from({ length: H }, () => Array(W).fill(-1));
  for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) {
    const [ix, iy] = toImg(x, y);
    const right = x > CX;
    if (inPoly(ix, iy, HEAD) || inPoly(ix, iy, HAND) || inPoly(ix, iy, foot)) { sil[y]![x] = 2; lab[y]![x] = -2; continue; }
    if (!(inPoly(ix, iy, body) || inPoly(ix, iy, ARM))) continue;
    sil[y]![x] = 1;
    const i = pieces.findIndex((p) => inPoly(ix, iy, p.poly));
    if (i >= 0) {
      const p = pieces[i]!;
      const band = p.bands?.filter((b) => iy > b).length ?? 0;
      const k = p.merge ? pieces.findIndex((q) => q.merge === p.merge) : i;
      lab[y]![x] = ((k * 8 + band) * 2 + (right && p.seam !== false ? 1 : 0)) * 64 + i;
    }
  }
  // 조각에 안 걸린 칸은 가까운 조각을 따름
  for (let pass = 0; pass < 20; pass++) {
    let changed = false;
    const next = lab.map((r) => [...r]);
    for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) {
      if (sil[y]![x] !== 1 || lab[y]![x]! >= 0) continue;
      for (const [dx, dy] of N4) { const o = lab[y + dy]?.[x + dx]; if (o !== undefined && o >= 0 && (x > CX) === (x + dx > CX)) { next[y]![x] = o; changed = true; break; } }
    }
    for (let y = 0; y < H; y++) lab[y] = next[y]!;
    if (!changed) break;
  }
  const inBody = (x: number, y: number) => (sil[y]?.[x] ?? 0) > 0;
  const pieceOf = (l: number) => (l >= 0 ? pieces[l % 64] : undefined);
  const isBase = (x: number, y: number) => { const l = lab[y]?.[x] ?? -1; return !inBody(x, y) || l < 0 || !!pieceOf(l)?.base; };
  const key = (l: number) => Math.floor(l / 64);
  const g = blank(W, H);
  for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) {
    if (!inBody(x, y)) continue;
    const l = lab[y]![x]!;
    // 바탕: 머리·손·발, 목·발목, 실루엣 가장자리 2칸, 조각 사이 틈 2칸(양쪽 1칸씩)
    if (isBase(x, y)) { g[y]![x] = 'b'; continue; }
    let gap = false;
    for (let dy = -GAP; dy <= GAP && !gap; dy++) for (let dx = -GAP; dx <= GAP && !gap; dx++) {
      const xx = x + dx, yy = y + dy;
      const edge = !inBody(xx, yy) || sil[yy]![xx] === 2 || isBase(xx, yy);
      if (edge) gap = Math.max(Math.abs(dx), Math.abs(dy)) <= EDGE;
      else if (Math.max(Math.abs(dx), Math.abs(dy)) <= 1 && key(lab[yy]![xx]!) !== key(l)) gap = true;
    }
    if (gap) { g[y]![x] = 'b'; continue; }
    const piece = pieceOf(l);
    g[y]![x] = piece?.group && on.has(piece.group) ? 'r' : 'f';
  }
  if (spec.heart) drawHeart(g);
  return g;
}
