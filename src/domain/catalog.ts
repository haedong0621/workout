export const CATALOG: readonly CatalogEntry[] = Object.entries(BY_PART).flatMap(([part, rows]) =>
  rows.map(([n, name, toggle, aka]) => ({
    id: 'seed-' + n, name, part, toggle,
    equip: equipOf(name, toggle),
    aka: aka ? aka.split(',').map((s) => s.trim()).filter(Boolean) : [],
  })),
);

/** 토글 운동의 기본 무게 방식 (맨몸은 고른 옵션에 따라 바뀜) */
export const kindFor = (toggle: ExerciseToggle | null, opt?: string): ExerciseKind =>
  toggle !== 'body' ? 'normal' : opt === '중량' ? 'bodyweight' : 'assist';

/** 옵션을 고른 때의 제목: 바벨 런지 → 스미스 런지 / 머신 레그 프레스 (핀) / 어시스트 딥스 */
export function optionTitle(name: string, toggle: ExerciseToggle | null | undefined, opt: string | undefined): string {
  if (!toggle || !opt) return name;
  if (toggle === 'bar') return opt === '바벨' ? name : name.replace(/^바벨 /, opt + ' ');
  if (toggle === 'machine') return `${name} (${opt})`;
  return `${opt} ${name}`;
}

/** 이름 비교용: 띄어쓰기·괄호·표기 차이 없애기 (이지 바 = 이지바, 푸쉬 = 푸시) */
export const nameKey = (s: string) => s.replace(/[\s()[\]]/g, '').replace(/푸쉬/g, '푸시').toLowerCase();

export function findCatalog(name: string): CatalogEntry | undefined {
  const k = nameKey(name);
  return CATALOG.find((e) => nameKey(e.name) === k) ?? CATALOG.find((e) => e.aka.some((a) => nameKey(a) === k));
}
