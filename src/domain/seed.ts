/** 새로 설치할 때 넣는 기본 운동 (id는 catalog.ts에 고정) */
export function seedExercises(now = Date.now()): Exercise[] {
  return CATALOG.map((e, i) => ({
    id: e.id,
    name: e.name, part: e.part, equip: e.equip,
    kind: kindFor(e.toggle),
    rest: null,
    imageId: null,
    memo: '', memoAt: null,
    fav: false, pinned: [],
    seed: true,
    createdAt: now + i,
    toggle: e.toggle, aka: e.aka,
  }));
}
